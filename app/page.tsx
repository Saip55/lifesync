// A small, static view of the critic pass: draft claims on the left, checked claims on the right.
function FactCheckIllustration() {
  const rows = [
    { claim: "Blood thinner + aspirin raises bleeding risk", status: "verified" as const },
    { claim: "Take 5 mg of the new medicine twice daily", status: "removed" as const },
    { claim: "Chest heaviness can signal a heart problem", status: "verified" as const },
    { claim: "Shelter open at the ward school", status: "unverified" as const },
  ];
  const chip = {
    verified: { label: "Verified", cls: "bg-low-soft text-low", Icon: CheckIcon },
    removed: { label: "Removed · guessed dose", cls: "bg-critical-soft text-critical", Icon: XIcon },
    unverified: { label: "Couldn’t verify", cls: "bg-cloud text-quiet", Icon: QuestionIcon },
  };

  return (
    <div className="rounded-card bg-board p-[10px]" aria-hidden="true">
      <div className="grid gap-[10px] sm:grid-cols-2">
        <div className="rounded-[8px] bg-canvas/60 p-4">
          <p className="text-utility font-medium text-quiet">Draft · Plan</p>
          <ul className="mt-3 divide-y divide-hairline">
            {rows.map((r) => (
              <li key={r.claim} className="py-3 text-caption text-charcoal">
                {r.claim}
              </li>
            ))}
          </ul>
        </div>
        <div className="rounded-[8px] bg-canvas p-4 shadow-window">
          <p className="flex items-center gap-1.5 text-utility font-medium text-graphite">
            <ShieldIcon size={14} /> After fact-check
          </p>
          <ul className="mt-3 divide-y divide-hairline">
            {rows.map((r) => {
              const c = chip[r.status];
              return (
                <li key={r.claim} className="py-3">
                  <span
                    className={`text-caption ${r.status === "removed" ? "text-ash line-through decoration-ash" : "text-graphite"}`}
                  >
                    {r.claim}
                  </span>
                  <span
                    className={`mt-1.5 flex w-fit items-center gap-1 rounded-badge px-1.5 py-0.5 text-utility font-medium ${c.cls}`}
                  >
                    <c.Icon size={12} strokeWidth={2.2} />
                    {c.label}
                  </span>
                </li>
              );
            })}
          </ul>
          <div className="mt-2 flex items-center gap-3 border-t border-hairline pt-3">
            <span className="text-utility text-quiet">Confidence</span>
            <span className="h-1.5 flex-1 rounded-full bg-black/[0.07]">
              <span className="block h-full w-[78%] rounded-full bg-graphite" />
            </span>
            <span className="font-mono text-[13px] text-graphite">78%</span>
          </div>
        </div>
      </div>
    </div>
  );
}
